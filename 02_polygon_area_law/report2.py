def rrec(grid, schedule, **kw):
    for r in recs:
        if r["grid"] == grid and r.get("schedule") == schedule and all(r.get(k) == v for k, v in kw.items()):
            return r
    return None


def rho_stats(r):
    rho = np.array(r["rho"])     # (seeds, E-1, T)
    js = np.array(r["jstar"]) / (r["T"] - 1)
    return rho, js


def eig_cell(r):
    if not r.get("eig"):
        return "skipped/none"
    E = r["eig"]
    f = lambda k: np.array([e[k] for e in E], dtype=float)
    return (f"nonzero {msd(f('n_nonzero'), '{:.1f}')}, non-real {msd(f('n_nonreal'), '{:.1f}')}, "
            f"median|arg| {msd(f('median_abs_arg'), '{:.4f}')}, max|arg| {msd(f('max_abs_arg'), '{:.4f}')} "
            f"(extra: |λ|=1 count {msd(f('n_unit_modulus'), '{:.1f}')}, rank M {msd(f('rank_M'), '{:.1f}')}, "
            f"#|λ|>1e-6 {msd(f('n_nonzero_1e-6'), '{:.1f}')}, max|λ| excl. unit {msd(f('max_modulus_excl_unit'), '{:.4f}')})")


def r_block(r, label):
    rho, js = rho_stats(r)
    E = r["E"]
    out(f"**{label}** (T={r['T']}, n={r['n']}, κ={r['kappa']}, d={r['d']}, E={E}, schedule={r['schedule']}"
        + (f", k={r['k']}, step scale={r['step_scale']}" if r.get("k") else "") + ")")
    out()
    out("| epoch e | ρ mean ± sd | 1−ρ mean | j*/(T−1) mean ± sd |")
    out("|---|---|---|---|")
    for e in range(2, E + 1):
        out(f"| {e} | {msd(rho[:, e - 2, :].ravel())} | {1 - rho[:, e - 2, :].mean():.4f} | {msd(js[:, e - 2, :].ravel())} |")
    out(f"| pooled 2–{E} | {msd(rho.ravel())} | {1 - rho.mean():.4f} | {msd(js.ravel())} |")
    out()


