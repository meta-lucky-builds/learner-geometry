def out(s=""):
    lines.append(s)


def mm(vals, fmt="{:.4g}"):
    v = [x for x in vals if x is not None and not (isinstance(x, float) and math.isnan(x))]
    if not v:
        return "n/a"
    return (fmt.format(float(np.median(v))) + " [" + fmt.format(min(v)) + ", " + fmt.format(max(v))
            + f"] (n={len(v)})")


def msd(vals, fmt="{:.4f}"):
    v = np.asarray(vals, dtype=float)
    return fmt.format(v.mean()) + " ± " + fmt.format(v.std(ddof=0))


def slope(x, y):
    return float(np.polyfit(np.log(x), np.log(y), 1)[0])


