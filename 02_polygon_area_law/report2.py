def frecs(grid, h=None, eps=None):
    return [r for r in recs if r["grid"] == grid and (h is None or r.get("h") == h)
            and (eps is None or r.get("eps") == eps)]


def pvals(grid, h, eps, poly, field):
    vals = []
    for r in frecs(grid, h, eps):
        p = (r.get("polys") or {}).get(poly)
        if p and p.get("status") == "OK" and field in p:
            vals.append(p[field])
    return vals


